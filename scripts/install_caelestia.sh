#!/usr/bin/env bash
# Caelestia (Hyprland + Quickshell) personal layer: user config, the Super+K
# shortcut palette, hand-forked shell QML, helper scripts, app configs, and the
# per-machine hardware file. Tracked files are symlinked from caelestia/ so edits
# stay in git; files that apps rewrite themselves are seeded once instead.
#
# Expects Caelestia itself to be installed already (the `desktop` step, or
# `caelestia install`). Never edits ~/.config/hypr, which upstream manages —
# hypr-vars.lua / hypr-user.lua are its documented override points.
#
# Env: REDETECT=1 regenerates ~/.config/caelestia/host.lua from the hardware.
#      WITH_XPPEN=1 forces the XP-Pen bits when the tablet is not plugged in.
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

SRC="$DOTFILES_DIR/caelestia"
info "🎨 Setting up Caelestia..."

if ! command -v caelestia >/dev/null 2>&1; then
  warn "Caelestia is not installed — skipping (run the desktop step first: ./install.sh --only desktop,caelestia)"
  exit 0
fi

# Link every file under $1 to the same relative path under $2. Per-file (not
# per-directory) so untracked neighbours — backups, generated state, upstream
# files — are left alone.
link_tree() { # $1=repo dir $2=target dir
  local rel
  while IFS= read -r rel; do
    link_file "$1/$rel" "$2/$rel"
  done < <(cd "$1" && find . -type f ! -path '*/__pycache__/*' -printf '%P\n' | sort)
}

# Copy every file under $1 to $2 unless it already exists: for files the owning
# app rewrites (HyprMod, xdg-mime), where a symlink would just get replaced.
seed_tree() { # $1=repo dir $2=target dir
  local rel
  while IFS= read -r rel; do
    if [ -e "$2/$rel" ]; then continue; fi
    run install -Dm644 "$1/$rel" "$2/$rel"
    ok "seeded ${2/#$HOME/\~}/$rel"
  done < <(cd "$1" && find . -type f -printf '%P\n' | sort)
}

eval "$("$DOTFILES_DIR/scripts/detect_hw.sh")"
[ "${WITH_XPPEN:-0}" = 1 ] && HW_XPPEN=1

# ------------------------------
# 1. User config (~/.config/caelestia)
# ------------------------------
# hypr-vars.lua / hypr-user.lua / shell.json / cli.json are Caelestia's
# documented override points; palette/ and scripts/ are the Super+K palette
# and personal workflows (notes, OCR, window finder, project picker).
info "🔗 Linking ~/.config/caelestia..."
link_tree "$SRC/config" "$HOME/.config/caelestia"

# ------------------------------
# 2. Machine-local hardware facts (~/.config/caelestia/host.lua, untracked)
# ------------------------------
# hypr-user.lua gates every hardware-specific block on this file, so the same
# tracked config works on a desktop, a plain laptop and the 2-in-1.
HOST_LUA="$HOME/.config/caelestia/host.lua"
lua_list() { local x out=""; for x in $1; do out="$out\"$x\", "; done; printf '{ %s}' "$out"; }
lua_str()  { [ -n "$1" ] && printf '"%s"' "$1" || printf 'nil'; }
lua_bool() { [ "$1" = 1 ] && printf 'true' || printf 'false'; }
if [ -f "$HOST_LUA" ] && [ -z "${REDETECT:-}" ]; then
  ok "host.lua exists (REDETECT=1 to regenerate)"
else
  info "🔍 Writing host.lua for: $HW_PRODUCT"
  is_2in1=0; { [ -n "$HW_TABLET_SWITCH" ] || [ "$HW_ACCEL" = 1 ]; } && is_2in1=1
  host_content="-- Generated by ~/dotfiles (install_caelestia.sh) on $(date +%F) for: $HW_PRODUCT
-- Machine-local and untracked: edit freely. Regenerate with
--   REDETECT=1 ~/dotfiles/install.sh --only caelestia
-- Read by hypr-user.lua; a missing key means \"this machine doesn't have it\".
return {
    panel         = $(lua_str "$HW_PANEL"),  -- internal display (pen/touch get pinned to it)
    screen_inputs = $(lua_list "$HW_SCREEN_INPUTS"),
    tablet_switch = $(lua_str "$HW_TABLET_SWITCH"),  -- 2-in-1 hinge (SW_TABLET_MODE)
    tablet_off    = $(lua_list "$HW_TABLET_OFF"),  -- disabled while folded
    auto_rotate   = $(lua_bool "$HW_ACCEL"),  -- iio-hyprland
    osk           = $(lua_bool "$is_2in1"),  -- wvkbd on-screen keyboard
    nvidia        = $(lua_bool "$HW_NVIDIA_ONLY"),  -- NVIDIA-only GPU: Hyprland env vars
    xppen         = $(lua_bool "$HW_XPPEN"),
}"
  if dry; then
    info "   [dry-run] would write $HOST_LUA:"; printf '%s\n' "$host_content" | sed 's/^/      /'
  else
    printf '%s\n' "$host_content" >"$HOST_LUA"
    ok "wrote $HOST_LUA"
  fi
fi

# ------------------------------
# 3. Helper scripts (~/.local/bin)
# ------------------------------
info "🔗 Linking helper scripts..."
for f in "$SRC"/bin/*; do
  [ -f "$f" ] || continue  # scripts only — never caches or folders
  link_file "$f" "$HOME/.local/bin/$(basename "$f")"
done

# The desktop config calls these by absolute path (hypr-vars.lua editor, the notes
# and project-picker workflows), because a Hyprland session's PATH is not a login
# shell's. Where the nvim/tmux steps put them varies — /usr/local/bin with sudo,
# ~/.local/bin without; tmux-revive links itself only on tmux's first run — so pin
# the expected paths to wherever they really are. (Found by the KDE VM test.)
pin_tool() { # $1=name $2=fallback target
  local want="$HOME/.local/bin/$1" have
  [ -e "$want" ] && return 0
  have=$(PATH="${PATH//$HOME\/.local\/bin/}" command -v "$1" 2>/dev/null || true)
  [ -n "$have" ] || have="$2"
  if [ -n "$have" ] && [ -x "$have" ]; then
    run ln -sfn "$have" "$want"; ok "linked ~/.local/bin/$1 → $have"
  else
    warn "$1 not found — the workflows that use it won't work until it's installed"
  fi
}
pin_tool nvim ""
pin_tool tmux-revive "$HOME/.tmux/plugins/tmux-revive/bin/tmux-revive"

# ------------------------------
# 4. Hand-forked shell QML (~/.config/quickshell/caelestia), guarded
# ------------------------------
# qs resolves ~/.config/quickshell/caelestia before the package's /etc/xdg tree,
# and only whole directories — so forking a few files means a "symlink farm": a
# link to every package file, with the forks linked over their originals.
# Upstream never creates it (on the Latitude it dates from the 2026-09-09 rescue),
# so build it here. Two risks, both handled at every login by caelestia-shell-guard:
# a caelestia-shell update adds files the farm lacks ("X is not a type"), or a fork
# stops loading against the newer API. See the guard's header for the escalation.
QS_DIR="$HOME/.config/quickshell/caelestia"
QS_PKG="/etc/xdg/quickshell/caelestia"
GUARD="$HOME/.local/bin/caelestia-shell-guard"
if [ ! -d "$QS_PKG" ]; then
  warn "caelestia-shell is not installed ($QS_PKG missing) — skipping the shell forks"
else
  if [ ! -d "$QS_DIR" ]; then
    info "🔗 Building the Quickshell symlink farm..."
    while IFS= read -r rel; do
      run mkdir -p "$(dirname "$QS_DIR/$rel")"
      run ln -s "$QS_PKG/$rel" "$QS_DIR/$rel"
    done < <(cd "$QS_PKG" && find . -type f -printf '%P\n' | sort)
  fi
  if [ -s "${XDG_STATE_HOME:-$HOME/.local/state}/caelestia/forks-reverted" ]; then
    # The guard switched them off after they failed to load; don't undo that blindly.
    warn "forks were reverted to stock after failing to load — left that way."
    warn "after merging upstream changes into them: caelestia-shell-guard restore && caelestia-shell-guard test"
  else
    info "🔗 Overlaying forked shell QML..."
    link_tree "$SRC/quickshell" "$QS_DIR"
    if dry; then :
    elif [ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ] && [ -n "${WAYLAND_DISPLAY:-}" ]; then
      info "🧪 Restarting the shell with the forks..."
      "$GUARD" test || warn "shell did not come up — see: caelestia shell -l"
    else
      info "   not inside Hyprland — the forks get checked at the next login"
    fi
  fi
fi

# ------------------------------
# 5. App configs
# ------------------------------
info "🔗 Linking app configs (ghostty, atuin, mise, uwsm)..."
link_tree "$SRC/home" "$HOME"
info "🌱 Seeding app-owned files (HyprMod settings, default apps, locale, cursor)..."
seed_tree "$SRC/seed" "$HOME"

# Thunar's "Open terminal here" action ships pointing at foot.
UCA="$HOME/.config/Thunar/uca.xml"
if [ -f "$UCA" ] && grep -q '<command>foot -D %f</command>' "$UCA"; then
  run sed -i -e 's|<command>foot -D %f</command>|<command>ghostty --working-directory=%f</command>|' \
             -e 's|Open the current directory in foot|Open the current directory in ghostty|' "$UCA"
  ok "Thunar terminal action → ghostty"
fi

# ------------------------------
# 6. OCR model for the palette's OCR workflow (workflows.py: ~/.local/share/tessdata)
# ------------------------------
# tessdata_fast, pinned by hash: same file the Latitude used (~4 MB, much quicker
# than the repo's tessdata_best-sized package).
TESS="$HOME/.local/share/tessdata/eng.traineddata"
TESS_SHA=7d4322bd2a7749724879683fc3912cb542f19906c83bcc1a52132556427170b2
if [ -f "$TESS" ] && echo "$TESS_SHA  $TESS" | sha256sum -c --status; then
  ok "OCR model present"
elif dry; then
  info "   [dry-run] would download tessdata_fast eng.traineddata"
else
  mkdir -p "$(dirname "$TESS")"
  if curl -fsSL -o "$TESS.part" https://github.com/tesseract-ocr/tessdata_fast/raw/main/eng.traineddata \
     && echo "$TESS_SHA  $TESS.part" | sha256sum -c --status; then
    mv "$TESS.part" "$TESS"; ok "downloaded OCR model"
  else
    rm -f "$TESS.part"; warn "OCR model download failed or changed upstream — OCR shortcut won't work until fixed"
  fi
fi

# ------------------------------
# 7. XP-Pen tablet (official driver; only with the tablet, or WITH_XPPEN=1)
# ------------------------------
if [ "$HW_XPPEN" = 1 ]; then
  info "🖊  XP-Pen: launcher entry, autostart mask, close-to-tray shim"
  link_tree "$SRC/xppen/home" "$HOME"
  # LD_PRELOAD'd by xppen-tablet so closing PenTablet keeps its tray icon.
  TRAY_SO="$HOME/.local/lib/xppen-tray/xppen-tray.so"
  link_file "$SRC/xppen-tray/shim.c" "$HOME/.local/lib/xppen-tray/shim.c"
  if [ -f "$TRAY_SO" ] && [ "$TRAY_SO" -nt "$SRC/xppen-tray/shim.c" ]; then
    ok "xppen-tray.so up to date"
  elif command -v gcc >/dev/null 2>&1; then
    run gcc -shared -fPIC -O2 -o "$TRAY_SO" "$SRC/xppen-tray/shim.c" -ldl
    ok "built xppen-tray.so"
  else
    warn "gcc not found — xppen-tablet will run without the close-to-tray shim"
  fi
fi

# ------------------------------
# 8. Wallpapers (private repo, cloned by hand — needs your GitHub SSH key)
# ------------------------------
WALLS="$HOME/Pictures/Wallpapers"
if [ -d "$WALLS/.git" ]; then
  ok "wallpapers present"
else
  info "🖼  Wallpapers are in a private repo. Once your SSH key is on GitHub:"
  info "      git clone git@github.com:ChaseBP/dotfiles-wallpaper.git ~/Pictures/Wallpapers && wall refresh"
fi

ok "Caelestia setup complete"
info "👉 Log out and back in (or reboot) so Hyprland, the shell and your groups all pick this up"
